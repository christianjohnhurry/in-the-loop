import {logoText} from './start';

const START = '<!-- logo:start (generated by scripts/readme-logo.ts) -->';
const END = '<!-- logo:end -->';

/**
 * Replaces the generated logo block in the README with the current start-page
 * logo.
 *
 * @param readme The README text, containing the logo markers.
 * @return The README with the logo block regenerated.
 */
export function syncLogo(readme: string): string {
  const from = readme.indexOf(START);
  const to = readme.indexOf(END);
  if (from < 0 || to < from) throw new Error('README.md: logo markers missing');
  const block = `${START}\n\`\`\`text\n${logoText().join('\n')}\n\`\`\`\n`;
  return readme.slice(0, from) + block + readme.slice(to);
}
